#!/usr/bin/env python3
"""Generate build files from manifest/effects.json.

Writes:
  cmake/Effects.cmake              - list of Airwindows sources + layout files to compile/embed
  src/generated/EffectList.gen.cpp - the effect registry used by the plugin

Run after editing the manifest:   python3 tools/gen_effects.py
CI runs:                          python3 tools/gen_effects.py --check   (fails if files are stale)
"""
import datetime
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "manifest" / "effects.json"
AW_DIR = "third_party/airwin_consolidated/autogen_airwin"
DOC_DIR = "third_party/airwin_consolidated/awpdoc"   # Airwindopedia texts (Effect info)
OUT_CMAKE = ROOT / "cmake" / "Effects.cmake"
OUT_CPP = ROOT / "src" / "generated" / "EffectList.gen.cpp"
OUT_FX_DIR = ROOT / "src" / "generated" / "fx"

ID_RE = re.compile(r"^[a-z0-9]+$")
SEMVER_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+$")
DATE_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
# Some original effects keep a little state in function-level 'static' variables, shared by every
# instance of that effect in the process (e.g. a tiny noise counter). That is original behaviour; the
# tests need to know about it, so it is detected here automatically.
SHARED_STATE_RE = re.compile(r"^\s*static\s+(?!const)", re.MULTILINE)


def fail(msg):
    print(f"gen_effects: ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    check = "--check" in sys.argv
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    effects = data["effects"]

    ids, names = set(), set()
    for e in effects:
        for key in ("id", "upstream", "version", "since", "released", "category", "included", "description"):
            if key not in e:
                fail(f"effect {e} is missing '{key}'")
        if "tail" in e and not (isinstance(e["tail"], (int, float)) and 0 <= e["tail"] <= 60):
            fail(f"'tail' of '{e['id']}' must be 0-60 seconds")
        if not DATE_RE.match(e["released"]):
            fail(f"'released' of '{e['id']}' must look like 2026-10-17")
        if not SEMVER_RE.match(e["since"]):
            fail(f"'since' of '{e['id']}' must look like 1.2.3")
        if not ID_RE.match(e["id"]):
            fail(f"id '{e['id']}' must be lower-case letters/digits only")
        if e["id"] in ids:
            fail(f"duplicate id '{e['id']}'")
        if e["upstream"] in names:
            fail(f"duplicate upstream name '{e['upstream']}'")
        ids.add(e["id"])
        names.add(e["upstream"])

    included = [e for e in effects if e["included"]]

    # "Latest" folder: Airwindows releases from the months before this Daylight_aw version.
    latest = data.get("latest", {})
    until = datetime.date.fromisoformat(latest.get("until", "2000-01-01"))
    months = int(latest.get("months", 6))
    start = until - datetime.timedelta(days=round(months * 30.44))
    def is_latest(e):
        return start < datetime.date.fromisoformat(e["released"]) <= until

    sources = []
    for e in included:
        n = e["upstream"]
        for f in (f"{n}.cpp", f"{n}Proc.cpp", f"{n}.h"):
            if not (ROOT / AW_DIR / f).exists():
                fail(f"missing Airwindows source {AW_DIR}/{f} for '{e['id']}'")
        sources += [f"{AW_DIR}/{n}.cpp", f"{AW_DIR}/{n}Proc.cpp"]

    layouts = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "layouts").glob("*.json"))
    for lay in layouts:
        lid = pathlib.Path(lay).stem
        if lid not in ids:
            fail(f"layout file {lay} does not match any effect id")

    # One small factory file per effect: every Airwindows header gets its own translation unit,
    # so macros one effect defines (e.g. THREEBYTHREE) can never leak into another effect.
    factories = {}
    for e in included:
        n, eid = e["upstream"], e["id"]
        factories[OUT_FX_DIR / f"{eid}.cpp"] = "\n".join([
            "// GENERATED by tools/gen_effects.py - do not edit by hand.",
            f'#include "autogen_airwin/{n}.h"',
            "#include <memory>",
            "",
            "namespace dlaw::gen",
            "{",
            f"std::unique_ptr<AirwinConsolidatedBase> make_{eid}() {{ return std::make_unique<airwinconsolidated::{n}::{n}> (0); }}",
            f"int params_{eid}() {{ return airwinconsolidated::{n}::kNumParameters; }}",
            "} // namespace dlaw::gen",
            ""])

    cmake = ["# GENERATED by tools/gen_effects.py from manifest/effects.json - do not edit by hand.",
             "set(DAYLIGHT_EFFECT_SOURCES"]
    cmake += [f"    {s}" for s in sources]
    cmake += [f"    {p.relative_to(ROOT).as_posix()}" for p in factories]
    cmake += [")", "", "set(DAYLIGHT_LAYOUT_FILES"]
    cmake += [f"    {l}" for l in layouts]
    cmake += [")", "", "# pairs: source file, embedded name", "set(DAYLIGHT_DOC_FILES"]
    for e in included:
        doc = f"{DOC_DIR}/{e['upstream']}.txt"
        if (ROOT / doc).exists():
            cmake.append(f"    {doc} doc_{e['id']}.txt")
        else:
            print(f"gen_effects: note: no Airwindopedia text for '{e['id']}' ({doc})")
    cmake += [")", ""]
    cmake_text = "\n".join(cmake)

    cpp = ["// GENERATED by tools/gen_effects.py from manifest/effects.json - do not edit by hand.",
           '#include "../dsp/EffectRegistry.h"', "", "namespace dlaw::gen", "{"]
    for e in included:
        cpp.append(f"std::unique_ptr<AirwinConsolidatedBase> make_{e['id']}(); int params_{e['id']}();")
    cpp += ["} // namespace dlaw::gen", "", "namespace dlaw", "{", "const std::vector<EffectInfo>& getAllEffects()", "{",
            "    static const std::vector<EffectInfo> list {"]
    for e in included:
        n, eid = e["upstream"], e["id"]
        shared = bool(SHARED_STATE_RE.search((ROOT / AW_DIR / f"{n}Proc.cpp").read_text(encoding="utf-8", errors="replace")))
        cpp.append(
            f"        {{ {c_str(eid)}, {c_str(n)}, {c_str(e['category'])}, {c_str(e['description'])}, "
            f"{int(e['version'])}, {c_str(e['since'])}, {float(e.get('tail', 0)):.1f}, {'true' if e.get('dither') else 'false'}, "
            f"{'true' if shared else 'false'}, {'true' if is_latest(e) else 'false'}, gen::params_{eid}(), &gen::make_{eid} }},")
    cpp += ["    };", "    return list;", "}", "} // namespace dlaw", ""]
    cpp_text = "\n".join(cpp)

    outputs = {OUT_CMAKE: cmake_text, OUT_CPP: cpp_text, **factories}
    stale_fx = [p for p in OUT_FX_DIR.glob("*.cpp") if p not in factories] if OUT_FX_DIR.exists() else []

    if check:
        stale = [p for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != t] + stale_fx
        if stale:
            fail("generated files are out of date, run tools/gen_effects.py: " + ", ".join(map(str, stale[:5])))
        print(f"gen_effects: OK ({len(included)} effects included)")
        return

    changed = False
    for path, text in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:   # untouched files = no rebuild
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            changed = True
    for p in stale_fx:
        p.unlink()
        changed = True
    print(f"gen_effects: {'wrote' if changed else 'up to date:'} {len(included)} effects, {len(layouts)} layouts")


if __name__ == "__main__":
    main()
